const CODES = new Set(Object.values(US_STATES));

/** "Ohio" / "ohio" / "OH" -> "OH"; anything else -> null. */
export function stateCodeFromRegion(region: string | null | undefined): string | null {
  if (!region) return null;
  const trimmed = region.trim();
  const upper = trimmed.toUpperCase();
  if (upper.length === 2 && CODES.has(upper)) return upper;
  return US_STATES[trimmed.toLowerCase()] ?? null;
}
